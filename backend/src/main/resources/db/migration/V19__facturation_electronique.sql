-- Facturation electronique (Peppol BIS Billing 3.0, obligatoire entre entreprises belges depuis 2026).

-- Donnees de facturation de l'institution cliente, saisies par l'administrateur.
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS raison_sociale VARCHAR(255);
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS numero_entreprise VARCHAR(20);
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS adresse_rue VARCHAR(255);
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS code_postal VARCHAR(20);
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS ville VARCHAR(120);
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS pays VARCHAR(2);
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS email_facturation VARCHAR(255);

-- Une facture par achat paye. Les donnees de l'acheteur sont figees a l'emission :
-- une facture ne change plus, meme si l'institution modifie ensuite ses informations.
CREATE TABLE IF NOT EXISTS factures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(20),
    annee INTEGER,
    sequence INTEGER,
    institution_id BIGINT NOT NULL REFERENCES institutions(id),
    pack_id BIGINT NOT NULL REFERENCES packs_credits(id),
    date_emission DATE NOT NULL,
    description VARCHAR(255) NOT NULL,
    quantite INTEGER NOT NULL,
    montant_ht NUMERIC(10,2) NOT NULL,
    taux_tva NUMERIC(5,2) NOT NULL,
    montant_tva NUMERIC(10,2) NOT NULL,
    montant_ttc NUMERIC(10,2) NOT NULL,
    devise VARCHAR(3) NOT NULL,
    statut VARCHAR(20) NOT NULL,
    acheteur_nom VARCHAR(255),
    acheteur_numero_entreprise VARCHAR(20),
    acheteur_adresse_rue VARCHAR(255),
    acheteur_code_postal VARCHAR(20),
    acheteur_ville VARCHAR(120),
    acheteur_pays VARCHAR(2),
    xml_ubl TEXT,
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_factures_pack UNIQUE (pack_id),
    CONSTRAINT uk_factures_numero UNIQUE (numero),
    CONSTRAINT uk_factures_annee_sequence UNIQUE (annee, sequence),
    CONSTRAINT ck_factures_statut CHECK (statut IN ('A_COMPLETER', 'EMISE'))
);

CREATE INDEX IF NOT EXISTS idx_factures_institution_id ON factures(institution_id);

-- Compteur annuel : la numerotation des factures doit etre continue, sans trou ni doublon.
CREATE TABLE IF NOT EXISTS compteurs_factures (
    annee INTEGER PRIMARY KEY,
    dernier_numero INTEGER NOT NULL
);
